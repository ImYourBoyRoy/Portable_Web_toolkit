/**
 * `package-updater migrate`: convert a site from npm (or yarn/bun) to pnpm in place, so a model never has to hand-build it.
 *
 * What it does (dry-run unless --apply):
 *   1. `pnpm import` converts the existing lockfile (package-lock.json / yarn.lock) so resolved versions are kept.
 *   2. Writes pnpm-workspace.yaml: pnpm 12 ignores the package.json "pnpm" field, so build allowlist (allowBuilds) and
 *      overrides live there. allowBuilds comes from npm's allowScripts / bun's trustedDependencies / pnpm's old
 *      onlyBuiltDependencies, plus the toolkit's known native set (esbuild, sharp, workerd) when the site depends on them.
 *      Nothing else is auto-approved: an unknown build script fails the install and is REPORTED for a decision.
 *   3. Rewrites scripts: npm run -> pnpm run, npm install -D -> pnpm add -D, npm ci -> pnpm install --frozen-lockfile,
 *      npx -> pnpm exec (pnpm dlx for @astrojs/upgrade), npm update -> pnpm update. Removes a packageManager pin to npm.
 *   4. Installs and verifies (check + build). A failure restores every touched file and re-installs with the old manager.
 *   5. Reports (does not edit) other files that still say npm: CI workflows, Dockerfiles, docs.
 */

import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { commandsFor, describe, detectPackageManager, isInstalled, runPackageManager } from '../../../shared/lib/package-manager.mjs';

const LOCKFILES = ['package-lock.json', 'npm-shrinkwrap.json', 'yarn.lock', 'bun.lock', 'bun.lockb', 'pnpm-lock.yaml'];
const KNOWN_NATIVE = ['esbuild', 'sharp', 'workerd'];

export function translateScript(command) {
  return String(command)
    .replace(/\bnpm run (?:--silent )?([\w:.-]+)/g, 'pnpm run $1')
    .replace(/\bnpm (?:install|i) (-D|--save-dev|-g|--global)\b/g, (match, flag) => (flag === '-g' || flag === '--global' ? 'pnpm add -g' : 'pnpm add -D'))
    .replace(/\bnpm (?:install|i) ([^&|;]*[^\s&|;])/g, 'pnpm add $1')
    .replace(/\bnpm (?:install|i)\b(?!\s+-)/g, 'pnpm install')
    .replace(/\bnpm ci\b/g, 'pnpm install --frozen-lockfile')
    .replace(/\bnpm update\b/g, 'pnpm update')
    .replace(/\bnpx (?:--yes |-y )?(@astrojs\/upgrade)/g, 'pnpm dlx $1')
    .replace(/\bnpx (?:--yes |-y )?([^\s&|;]+)/g, 'pnpm exec $1');
}

export function translateScripts(scripts = {}) {
  const out = {};
  const changed = [];
  for (const [name, command] of Object.entries(scripts)) {
    const next = translateScript(command);
    out[name] = next;
    if (next !== command) changed.push(name);
  }
  return { scripts: out, changed };
}

function resolveOverrideValue(value, pkg) {
  const text = String(value);
  if (text.startsWith('$')) return pkg.dependencies?.[text.slice(1)] ?? pkg.devDependencies?.[text.slice(1)] ?? null;
  return text;
}

export function buildWorkspaceYaml(pkg, { allow = [], deny = [] } = {}) {
  const builds = new Map();
  for (const [name, allowed] of Object.entries(pkg.allowScripts ?? {})) if (allowed) builds.set(name, true);
  for (const name of pkg.trustedDependencies ?? []) builds.set(name, true);
  for (const name of pkg.pnpm?.onlyBuiltDependencies ?? []) builds.set(name, true);
  for (const name of allow) builds.set(name, true);
  const dependencies = { ...pkg.dependencies, ...pkg.devDependencies };
  for (const name of KNOWN_NATIVE) if (name in dependencies || name === 'workerd' && 'wrangler' in dependencies || name === 'esbuild' && ('astro' in dependencies || 'vite' in dependencies) || name === 'sharp' && 'astro' in dependencies) builds.set(name, true);
  for (const name of deny) builds.set(name, false);
  const overrides = new Map();
  for (const [name, value] of Object.entries({ ...(pkg.overrides ?? {}), ...(pkg.pnpm?.overrides ?? {}) })) {
    const resolved = typeof value === 'string' ? resolveOverrideValue(value, pkg) : null;
    if (resolved) overrides.set(name, resolved);
  }
  const lines = ['# pnpm 12 settings (the package.json "pnpm" field is ignored). Generated by package-updater migrate.'];
  if (builds.size > 0) {
    lines.push('', '# Dependencies allowed to run install scripts. pnpm fails the install on any other build script;', '# review a new one before adding it here.', 'allowBuilds:');
    for (const name of [...builds.keys()].sort()) lines.push(`  ${/^[\w.-]+$/.test(name) ? name : `'${name}'`}: ${builds.get(name)}`);
  }
  if (overrides.size > 0) {
    lines.push('', 'overrides:');
    for (const [name, value] of [...overrides.entries()].sort((a, b) => a[0].localeCompare(b[0]))) lines.push(`  ${/^[\w.-]+$/.test(name) ? name : `'${name}'`}: '${value}'`);
  }
  return `${lines.join('\n')}\n`;
}

/** Files outside package.json that still mention npm; reported, never rewritten. */
export function findOtherNpmMentions(projectRoot) {
  const found = [];
  const candidates = [];
  const workflows = path.join(projectRoot, '.github', 'workflows');
  if (fs.existsSync(workflows)) for (const name of fs.readdirSync(workflows)) candidates.push(path.join(workflows, name));
  for (const name of ['Dockerfile', 'wrangler.toml', 'wrangler.jsonc', 'README.md', 'AGENTS.md', 'MEMORY.md', 'CLAUDE.md']) candidates.push(path.join(projectRoot, name));
  for (const file of candidates) {
    if (!fs.existsSync(file) || !fs.statSync(file).isFile()) continue;
    fs.readFileSync(file, 'utf8').split('\n').forEach((line, index) => {
      if (/\bnpm (run|ci|install|i|update|exec)\b|\bnpx\b/.test(line)) found.push(`${path.relative(projectRoot, file).split(path.sep).join('/')}:${index + 1}: ${line.trim().slice(0, 100)}`);
    });
  }
  return found;
}

/** Names from pnpm's `Ignored build scripts: a@1.0.0, b@2.0.0` failure text. */
export function parseIgnoredBuilds(output) {
  const match = /Ignored build scripts:\s*([\s\S]*?)(?:\n\s*\n|\n\s*help:|$)/.exec(String(output));
  if (!match) return [];
  return [...new Set(match[1].split(/[,\s]+/).map((item) => item.replace(/@[^@/]*$/, '').trim()).filter(Boolean))];
}

export function planMigration(projectRoot, { flagPm, allow = [], deny = [] } = {}) {
  const pkgFile = path.join(projectRoot, 'package.json');
  if (!fs.existsSync(pkgFile)) throw new Error(`package.json not found at ${pkgFile}`);
  const pkg = JSON.parse(fs.readFileSync(pkgFile, 'utf8'));
  const current = detectPackageManager(projectRoot, { flag: flagPm, installed: () => false, env: {} });
  const hasWorkspace = fs.existsSync(path.join(projectRoot, 'pnpm-workspace.yaml'));
  const lock = LOCKFILES.find((name) => fs.existsSync(path.join(projectRoot, name))) ?? null;
  const { scripts, changed } = translateScripts(pkg.scripts);
  const next = { ...pkg, scripts };
  if (typeof next.packageManager === 'string' && !next.packageManager.startsWith('pnpm')) delete next.packageManager;
  next.engines = { ...(next.engines ?? {}), pnpm: next.engines?.pnpm ?? '>=10' };
  const alreadyPnpm = lock === 'pnpm-lock.yaml' && hasWorkspaceOrNoNeed(pkg, hasWorkspace);
  return { pkg, next, scriptsChanged: changed, from: current.name === 'pnpm' && lock !== 'pnpm-lock.yaml' ? (lock === 'yarn.lock' ? 'yarn' : lock?.startsWith('bun') ? 'bun' : 'npm') : current.name, lock, hasWorkspace, workspaceYaml: buildWorkspaceYaml(pkg, { allow, deny }), alreadyPnpm, otherMentions: findOtherNpmMentions(projectRoot) };
}

function hasWorkspaceOrNoNeed(pkg, hasWorkspace) {
  return hasWorkspace || (Object.keys(buildWorkspaceYaml(pkg)).length > 0 && !/allowBuilds|overrides/.test(buildWorkspaceYaml(pkg)));
}

function snapshot(projectRoot, names) {
  return names.map((name) => path.join(projectRoot, name)).map((file) => ({ file, existed: fs.existsSync(file), content: fs.existsSync(file) ? fs.readFileSync(file) : null }));
}

function restore(saved) {
  for (const { file, existed, content } of saved) {
    if (existed) fs.writeFileSync(file, content);
    else fs.rmSync(file, { force: true });
  }
}

/**
 * @param {object} flags @param {{ runStepFn?: Function, log?: (text: string) => void, pnpmInstalled?: boolean }} [hooks]
 */
export async function runMigrate(flags = {}, hooks = {}) {
  const log = hooks.log ?? ((text) => process.stdout.write(text));
  const projectRoot = path.resolve(flags['project-root'] || '.');
  const apply = flags.apply === true || flags.apply === 'true';
  const target = String(flags.to || 'pnpm');
  if (target !== 'pnpm') throw new Error('migrate only converts to pnpm (--to pnpm).');
  const list = (value) => (typeof value === 'string' ? value.split(',').map((item) => item.trim()).filter(Boolean) : []);
  const plan = planMigration(projectRoot, { allow: list(flags['allow-builds']), deny: list(flags['deny-builds']) });
  if (plan.alreadyPnpm) {
    log('[migrate] already on pnpm (pnpm-lock.yaml and settings present); nothing to do.\n');
    return 0;
  }
  const lines = [`[migrate] ${projectRoot} | ${plan.from} -> pnpm | ${apply ? 'apply' : 'dry-run'}`];
  lines.push(plan.lock && plan.lock !== 'pnpm-lock.yaml' ? `lockfile ${plan.lock} -> pnpm-lock.yaml (pnpm import keeps resolved versions)` : 'no lockfile to import; pnpm will resolve fresh');
  lines.push(`pnpm-workspace.yaml: ${plan.hasWorkspace ? 'exists, kept' : `write (${(plan.workspaceYaml.match(/^  \S+:/gm) ?? []).length} entries)`}`);
  lines.push(`scripts rewritten: ${plan.scriptsChanged.length > 0 ? plan.scriptsChanged.join(', ') : 'none'}`);
  if (plan.otherMentions.length > 0) lines.push(`still mention npm (update by hand):\n  ${plan.otherMentions.slice(0, 12).join('\n  ')}`);
  log(`${lines.join('\n')}\n`);
  if (!apply) {
    log('[migrate] dry-run only. Re-run with --apply; any failure restores every file.\n');
    return 0;
  }
  if (!(hooks.pnpmInstalled ?? isInstalled('pnpm'))) {
    console.error('[migrate] pnpm is not installed. Install it first (corepack enable, or npm i -g pnpm), then re-run.');
    return 1;
  }

  const touched = ['package.json', 'pnpm-workspace.yaml', ...LOCKFILES];
  const saved = snapshot(projectRoot, touched);
  let lastOutput = '';
  const step = (args) => {
    if (hooks.runStepFn) {
      const result = hooks.runStepFn('pnpm', args, projectRoot);
      lastOutput = typeof result === 'object' && result ? String(result.output ?? '') : '';
      return typeof result === 'object' && result ? result.status : result;
    }
    // Output is captured so a failure can name the package; it is echoed only when something fails.
    const result = runPackageManager('pnpm', args, { spawnOptions: { cwd: projectRoot, timeout: 600_000, stdio: 'pipe' } });
    lastOutput = `${result.stdout ?? ''}\n${result.stderr ?? ''}`;
    if ((result.status ?? 1) !== 0) process.stderr.write(`${lastOutput.trim().split('\n').slice(-25).join('\n')}\n`);
    return result.status ?? 1;
  };
  const fail = (why) => {
    restore(saved);
    console.error(`[migrate] FAILED: ${why}. Restored package.json, pnpm-workspace.yaml and lockfiles.`);
    const old = plan.from;
    if (!flags['skip-install']) (hooks.runStepFn ? hooks.runStepFn(old, commandsFor(old).install(), projectRoot) : runPackageManager(old, commandsFor(old).install(), { spawnOptions: { cwd: projectRoot, timeout: 600_000 } }));
    return 1;
  };

  if (plan.lock && plan.lock !== 'pnpm-lock.yaml' && !plan.lock.startsWith('bun')) {
    log('[migrate] pnpm import\n');
    if (step(['import']) !== 0) return fail('pnpm import failed');
  }
  fs.writeFileSync(path.join(projectRoot, 'package.json'), `${JSON.stringify(plan.next, null, 2)}\n`, 'utf8');
  if (!plan.hasWorkspace) fs.writeFileSync(path.join(projectRoot, 'pnpm-workspace.yaml'), plan.workspaceYaml, 'utf8');
  if (!flags['skip-install']) {
    log(`[migrate] ${describe('pnpm', commandsFor('pnpm').install())}\n`);
    if (step(commandsFor('pnpm').install()) !== 0) {
      const ignored = parseIgnoredBuilds(lastOutput);
      if (ignored.length > 0) {
        return fail(`pnpm blocked install scripts it was not told about (ERR_PNPM_IGNORED_BUILDS): ${ignored.join(', ')}. Decide per package: trust it with --allow-builds ${ignored.join(',')} (it will run its install script), or block it with --deny-builds ${ignored.join(',')}`);
      }
      return fail('pnpm install failed');
    }
    if (!flags['skip-verify']) {
      for (const script of ['check', 'build']) {
        if (!plan.next.scripts?.[script]) continue;
        log(`[migrate] verify: pnpm run ${script}\n`);
        if (step(commandsFor('pnpm').run(script)) !== 0) return fail(`\`${script}\` failed under pnpm`);
      }
    }
  }
  for (const stale of ['package-lock.json', 'npm-shrinkwrap.json', 'yarn.lock']) fs.rmSync(path.join(projectRoot, stale), { force: true });
  log('[migrate] done: pnpm-lock.yaml, pnpm-workspace.yaml, pnpm scripts. Old lockfiles removed (restore from git if needed). Update the CI/hosting build commands listed above.\n');
  return 0;
}
