// ./scripts/discovery-postbuild.mjs
/**
 * Post-build discovery step. Run after the build and after the toolkit writes dist/client/_headers:
 *   node ./scripts/discovery-postbuild.mjs [dist/client]        (wire into `build:headers:prod`)
 * 1. Markdown twins: converts every built HTML page listed in /api/content.json to <page>/index.md.
 * 2. Whole-site bundle: /site.md (all pages in one Markdown document) and /api/site.json, so an agent can read the
 *    whole site in one request. List long pages in BUNDLE_SUMMARY_ONLY to replace their body with a pointer.
 * 3. Headers: appends a managed block to dist/client/_headers with per-page Link and Vary headers, Markdown twin headers
 *    (Content-Type, canonical Link), the API catalog content type, and CORS for public data files.
 * Fails (exit 1) when a page in the content index has no HTML, or when _headers would exceed Cloudflare's 100-rule limit.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { htmlToMarkdown } from './lib/html-to-markdown.mjs';

/** Page paths (for example '/prompts/') whose body is replaced by a pointer in the whole-site bundle. */
const BUNDLE_SUMMARY_ONLY = new Set([]);
/** Public data files that get `Access-Control-Allow-Origin: *` when they exist in the build. */
const CORS_FILES = ['/.well-known/mcp/server-card.json', '/api/content.json', '/api/openapi.json', '/api/site.json', '/llms.txt', '/llms-full.txt'];

const BEGIN = '# BEGIN discovery headers (generated by scripts/discovery-postbuild.mjs; do not edit)';
const END = '# END discovery headers';
const MAX_RULES = 100;
const yaml = (value) => JSON.stringify(String(value ?? ''));
const pageFile = (distDir, pagePath, name) => path.join(distDir, pagePath === '/' ? name : `${pagePath.replace(/^\//, '')}${name}`);

export function readContentIndex(distDir) {
  const raw = JSON.parse(fs.readFileSync(path.join(distDir, 'api/content.json'), 'utf8'));
  const routes = Array.isArray(raw) ? raw : raw.routes;
  if (!Array.isArray(routes)) throw new Error('api/content.json must be an array or an object with a "routes" array');
  const site = (Array.isArray(raw) ? '' : raw.siteUrl) || new URL(routes[0]?.url || 'https://example.invalid').origin;
  return { site, siteName: Array.isArray(raw) ? '' : raw.siteName || '', routes };
}

export function buildMarkdownTwins(distDir, index) {
  const twins = [];
  for (const route of index.routes) {
    const htmlFile = pageFile(distDir, route.path, 'index.html');
    if (!fs.existsSync(htmlFile)) {
      // Server-rendered pages (prerender = false) have no static HTML and no markdownUrl in content.json: skip them.
      if (!route.markdownUrl) { console.log(`discovery: skipped ${route.path} (server-rendered, no static HTML)`); continue; }
      throw new Error(`content.json lists ${route.path} with a Markdown URL but ${htmlFile} does not exist`);
    }
    const { markdown } = htmlToMarkdown(fs.readFileSync(htmlFile, 'utf8'), { baseUrl: index.site });
    const heading = /^# /m.test(markdown) ? '' : `# ${route.title}\n\n`;
    const url = route.url || new URL(route.path, `${index.site}/`).href;
    const body = [
      '---',
      `title: ${yaml(route.title)}`,
      `description: ${yaml(route.description)}`,
      `canonical: ${url}`,
      ...(route.lastmod ? [`updated: ${route.lastmod}`] : []),
      '---',
      '',
      `${heading}${markdown}`,
      '',
      '---',
      `Canonical page: ${url}`,
      `Site index for agents: ${index.site}/llms.txt`,
    ].join('\n');
    fs.writeFileSync(pageFile(distDir, route.path, 'index.md'), `${body.trimEnd()}\n`);
    twins.push({
      path: route.path, markdownPath: route.path === '/' ? '/index.md' : `${route.path}index.md`, url,
      markdownUrl: route.markdownUrl || new URL(route.path === '/' ? '/index.md' : `${route.path}index.md`, `${index.site}/`).href,
      title: route.title, description: route.description, lastmod: route.lastmod ?? null, type: route.type ?? 'page',
      markdown: `${heading}${markdown}`.trim(),
    });
  }
  return twins;
}

const demote = (markdown) => {
  let inFence = false;
  return markdown.split('\n').map((line) => {
    if (line.startsWith('```')) inFence = !inFence;
    return !inFence && /^#{1,5} /.test(line) ? `#${line}` : line;
  }).join('\n');
};

export function buildSiteBundle(distDir, index, twins) {
  const body = (twin) => (BUNDLE_SUMMARY_ONLY.has(twin.path)
    ? `${twin.description}\n\nThe full text of this page is long. Read it at ${twin.markdownUrl}.`
    : twin.markdown);
  const name = index.siteName || new URL(index.site).hostname;
  const newest = twins.map((twin) => twin.lastmod).filter(Boolean).sort().at(-1) ?? null;
  const short = (title) => title.replace(new RegExp(`\\s*\\|\\s*${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`), '');

  const markdown = [
    `# ${name}: the whole site in one document`,
    '',
    `> Every public page of ${index.site} as Markdown, in site order${newest ? `; newest page change ${newest}` : ''}. Per-page versions: <page>/index.md. Index for agents: ${index.site}/llms.txt.`,
    '',
    '## Contents',
    ...twins.map((twin) => `- ${short(twin.title)}: ${twin.url}`),
    ...twins.flatMap((twin) => ['', '---', '', `## Page: ${short(twin.title)}`, `Source: ${twin.url}${twin.lastmod ? ` (updated ${twin.lastmod})` : ''}`, '', demote(body(twin))]),
  ].join('\n');

  const siteJson = {
    site: index.site,
    description: `Every public page of ${index.site} as Markdown in one response. Per-page Markdown: <page>/index.md. Overview: /llms.txt.`,
    pageCount: twins.length,
    newestPageChange: newest,
    pages: twins.map((twin) => ({
      path: twin.path, url: twin.url, markdownUrl: twin.markdownUrl, type: twin.type, title: twin.title,
      description: twin.description, lastmod: twin.lastmod, markdown: body(twin),
    })),
  };
  fs.mkdirSync(path.join(distDir, 'api'), { recursive: true });
  fs.writeFileSync(path.join(distDir, 'site.md'), `${markdown.trimEnd()}\n`);
  fs.writeFileSync(path.join(distDir, 'api/site.json'), `${JSON.stringify(siteJson, null, 2)}\n`);
  return { markdownBytes: Buffer.byteLength(markdown), jsonBytes: Buffer.byteLength(JSON.stringify(siteJson)) };
}

const rule = (pattern, headers) => `${pattern}\n${Object.entries(headers).map(([header, value]) => `  ${header}: ${value}`).join('\n')}`;

export function writeLinkHeaders(distDir, index, twins) {
  const site = index.site;
  const hasCatalog = fs.existsSync(path.join(distDir, '.well-known/api-catalog'));
  const hasOpenApi = fs.existsSync(path.join(distDir, 'api/openapi.json'));
  const hasLlms = fs.existsSync(path.join(distDir, 'llms.txt'));
  const extras = [
    ...(hasCatalog ? [`<${site}/.well-known/api-catalog>; rel="api-catalog"`] : []),
    ...(hasOpenApi ? [`<${site}/api/openapi.json>; rel="service-desc"; type="application/json"`] : []),
    ...(hasLlms ? [`<${site}/llms.txt>; rel="describedby"; type="text/plain"`] : []),
  ];

  const rules = [];
  for (const twin of twins) {
    rules.push(rule(twin.path, {
      Link: [`<${twin.url}>; rel="canonical"`, `<${twin.markdownUrl}>; rel="alternate"; type="text/markdown"`, ...extras].join(', '),
      Vary: 'Accept',
    }));
  }
  for (const twin of twins) {
    rules.push(rule(twin.markdownPath, { 'Content-Type': 'text/markdown; charset=utf-8', Link: `<${twin.url}>; rel="canonical"`, 'Access-Control-Allow-Origin': '*' }));
  }
  rules.push(rule('/site.md', { 'Content-Type': 'text/markdown; charset=utf-8', 'Access-Control-Allow-Origin': '*' }));
  if (hasCatalog) {
    rules.push(rule('/.well-known/api-catalog', {
      'Content-Type': 'application/linkset+json; profile="https://www.rfc-editor.org/info/rfc9727"',
      'Access-Control-Allow-Origin': '*',
    }));
  }
  for (const file of CORS_FILES) {
    if (fs.existsSync(path.join(distDir, file.slice(1)))) rules.push(rule(file, { 'Access-Control-Allow-Origin': '*' }));
  }

  const headersFile = path.join(distDir, '_headers');
  const current = fs.existsSync(headersFile) ? fs.readFileSync(headersFile, 'utf8') : '';
  const escapedBegin = BEGIN.replace(/[()]/g, '\\$&');
  const stripped = current.replace(new RegExp(`\\n?${escapedBegin}[\\s\\S]*?${END}\\n?`), '\n');
  const next = `${stripped.trimEnd()}\n\n${BEGIN}\n${rules.join('\n\n')}\n${END}\n`;

  const total = next.split('\n').filter((line) => line && !line.startsWith('#') && !/^\s/.test(line)).length;
  if (total > MAX_RULES) throw new Error(`_headers would contain ${total} rules; Cloudflare allows ${MAX_RULES}. Move per-page Link headers into the Worker (src/worker.ts).`);
  if (Math.max(...next.split('\n').map((line) => line.length)) > 2000) throw new Error('_headers has a line over 2000 characters; Cloudflare allows 2000.');
  fs.writeFileSync(headersFile, next);
  return { rules: total };
}

export function run(distDir = path.resolve(process.cwd(), 'dist/client')) {
  const index = readContentIndex(distDir);
  const twins = buildMarkdownTwins(distDir, index);
  const bundle = buildSiteBundle(distDir, index, twins);
  const headers = writeLinkHeaders(distDir, index, twins);
  console.log(`discovery: wrote ${twins.length} Markdown twins, site.md (${Math.round(bundle.markdownBytes / 1024)} KB), api/site.json (${Math.round(bundle.jsonBytes / 1024)} KB) and ${headers.rules} total _headers rules`);
  return { twins, bundle, headers };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  try { run(process.argv[2] ? path.resolve(process.argv[2]) : undefined); } catch (error) { console.error(`discovery: ${error.message}`); process.exit(1); }
}
